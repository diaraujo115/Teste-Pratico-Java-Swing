    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed
         String nome = txtNome.getText().trim();
        String dataTexto = txtDataAdmissao.getText().trim();
        String salarioTexto = txtSalario.getText().trim();
        boolean status = chkStatus.isSelected();

        if (nome.isEmpty() || dataTexto.isEmpty() || salarioTexto.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Preencha todos os campos.", "Erro", JOptionPane.WARNING_MESSAGE);
            return;
        }

        try {
            LocalDate dataAdmissao = LocalDate.parse(dataTexto);
            BigDecimal salario = new BigDecimal(salarioTexto.replace(",", "."));

            Funcionario funcionario = new Funcionario(nome, dataAdmissao, salario, status);

            FuncionarioDAO dao = new FuncionarioDAO();
            dao.cadastrar(funcionario);

            JOptionPane.showMessageDialog(this, "Funcionário cadastrado com sucesso!");

            txtNome.setText("");
            txtDataAdmissao.setText("");
            txtSalario.setText("");
            chkStatus.setSelected(false);

            carregarTabela();

        } catch (DateTimeParseException e) {
            JOptionPane.showMessageDialog(this, "Data inválida. Use o formato AAAA-MM-DD.", "Erro", JOptionPane.WARNING_MESSAGE);
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Salário inválido. Digite apenas números.", "Erro", JOptionPane.WARNING_MESSAGE);
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Erro ao cadastrar: " + e.getMessage(), "Erro", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnSalvarActionPerformed

