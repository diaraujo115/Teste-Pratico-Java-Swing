    private DefaultTableModel tableModel;

    private void carregarTabela() {
    
    tableModel = new DefaultTableModel(new Object[]{"ID", "Nome", "Data Admissão", "Salário", "Status"}, 0);
    tblFuncionarios.setModel(tableModel);

    try {
        FuncionarioDAO dao = new FuncionarioDAO();
        List<Funcionario> lista = dao.listarTodos();

        for (Funcionario f : lista) {
            tableModel.addRow(new Object[]{
                f.getId(),
                f.getNome(),
                f.getDataAdmissao().toString(),
                f.getSalario(),
                f.isStatus() ? "Ativo" : "Inativo"
            });
        }
    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this, "Erro ao carregar funcionários: " + e.getMessage(), "Erro", JOptionPane.ERROR_MESSAGE);
    }
}
